// Get hidden gems for a specific state
export const getHiddenGemsForState = (stateName) => {
    if (!stateName) return [];

    const normalizedName = stateName.trim();
    const directMatch = HIDDEN_GEMS_DATA[normalizedName];
    if (directMatch) return directMatch;

    // Handle common variations
    const variations = {
        "Jammu and Kashmir": "J & K",
        "Jammu & Kashmir": "J & K",
        "Andaman and Nicobar": "Andaman and Nicobar Islands",
        "Andaman & Nicobar": "Andaman and Nicobar Islands",
    };

    if (variations[normalizedName]) {
        return HIDDEN_GEMS_DATA[variations[normalizedName]] || [];
    }

    // Partial match
    for (const [key, gems] of Object.entries(HIDDEN_GEMS_DATA)) {
        if (key.toLowerCase().includes(normalizedName.toLowerCase()) ||
            normalizedName.toLowerCase().includes(key.toLowerCase())) {
            return gems;
        }
    }

    return [];
};

